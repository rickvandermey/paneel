// Regenerates libs/editor/src/lib/icon-picker/simple-icons-names.ts after upgrading simple-icons.
import { readFileSync, writeFileSync } from 'node:fs';

const data = JSON.parse(readFileSync('node_modules/simple-icons/data/simple-icons.json', 'utf8'));
const list = data.map((icon) => [icon.title, icon.slug, icon.hex]);
writeFileSync(
	'libs/editor/src/lib/icon-picker/simple-icons-names.ts',
	`// Generated by tools/scripts/generate-simple-icons-names.mjs from simple-icons. Do not edit.\n/** [title, slug, brand hex] per logo; loaded lazily by the Logo tab. */\nexport const SIMPLE_ICONS: readonly (readonly [string, string, string])[] = ${JSON.stringify(list)};\n`,
);
console.log(`${list.length} logos written`);
