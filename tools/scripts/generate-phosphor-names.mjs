// Regenerates libs/editor/src/lib/icon-picker/phosphor-names.ts after upgrading @phosphor-icons/web.
import { readFileSync, writeFileSync } from 'node:fs';

const source = JSON.parse(
	readFileSync('node_modules/@phosphor-icons/web/src/Phosphor.json', 'utf8'),
);
const names = [
	...new Set(
		source.iconSets[0].selection
			.map((entry) => entry.name)
			.filter((name) => typeof name === 'string'),
	),
].sort();
writeFileSync(
	'libs/editor/src/lib/icon-picker/phosphor-names.ts',
	`// Generated by tools/scripts/generate-phosphor-names.mjs from @phosphor-icons/web. Do not edit.\nexport const PHOSPHOR_ICON_NAMES: readonly string[] = ${JSON.stringify(names)};\n`,
);
console.log(`${names.length} icon names written`);
